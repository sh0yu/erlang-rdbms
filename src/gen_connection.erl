%%%-------------------------------------------------------------------
%%% @doc
%%% クライアント向けの接続API。
%%% 1接続につきquery_execプロセスが1つ起動し、そのプロセスが
%%% 1つのトランザクションを実行する。
%%% @end
%%%-------------------------------------------------------------------
-module(gen_connection).

-export([connect/0, disconnect/1]).

%%----------------------------------------------------------------------
%% @doc 接続を作る。
%% Returns: {ok, Pid} | {error, Reason}
%%----------------------------------------------------------------------
connect() ->
    supervisor:start_child(query_exec_sup, []).

%%----------------------------------------------------------------------
%% @doc 接続を閉じる。未コミットのトランザクションはロールバックされる。
%%----------------------------------------------------------------------
disconnect(Pid) ->
    query_exec:stop(Pid).
