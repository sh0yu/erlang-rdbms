-module(tether_book).

-export([chapters/0, flat/0, get/1]).

%%%===================================================================
%%% 公開
%%%===================================================================

chapters() -> deep(raw()).

%% 全項目を平らに並べる(目次用)
flat() ->
    [I#{chapter => maps:get(title, C)}
     || C <- chapters(), I <- maps:get(items, C)].

get(Id) ->
    case [I || I <- flat(), maps:get(id, I) =:= Id] of
        [I | _] -> I;
        []      -> none
    end.

%% 文字列(符号位置のリスト)を UTF-8 バイナリへ。地図もリストも辿る。
%%
%% **鍵も変換すること。** 値だけ変換すると、文字列の鍵がリストのまま残り、
%% JSON にする段で落ちる(実際に踏んだ。本文だけ空で 200 が返った)。
deep(M) when is_map(M) ->
    maps:fold(fun(K, V, A) -> A#{deep_key(K) => deep(V)} end, #{}, M);
deep([])                -> [];
deep(L) when is_list(L) ->
    case lists:all(fun(X) -> is_integer(X) andalso X >= 0 end, L) of
        true  -> unicode:characters_to_binary(L);
        false -> [deep(X) || X <- L]
    end;
deep(X) -> X.

deep_key(K) when is_atom(K) -> K;
deep_key(K)                 -> deep(K).

