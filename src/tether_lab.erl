%%%-------------------------------------------------------------------
%%% @doc
%%% 分散データベースで起きる現象を、方式ごとに並べて見せる。
%%%
%%% **このモジュールは純粋である。** 同じ出来事の列を、複数の
%%% 競合解決の方式に当てて、結果が分かれるところを出す。
%%%
%%% 方式:
%%%   naive     再送を吸収しない。素朴な実装
%%%   lww       時刻の大きい方が勝つ(Cassandra)
%%%   crdt      演算を統合する。収束するが不変条件は守らない
%%%   cas       前提が違えば中止する(古典のRDBMS)。協調が要る
%%%   log       全順序のログに載せて再実行する
%%%   escrow    先に持ち分を配る。協調なしで下限を守る
%%%   session   通番で再送を吸収する(tether)
%%%
%%% ここで示すのは**方式の帰結**であって、tether の実装の動作ではない。
%%% 実装の動作は画面のもう一方(端末2台とサーバ)で見る。
%%% @end
%%%-------------------------------------------------------------------
-module(tether_lab).

-export([all/0, ids/0, get/1]).

%%%===================================================================
%%% 骨組み
%%%===================================================================

%% 1手順 = 語り + 状態の変換
run(Init, Steps) ->
    {Rev, _} = lists:foldl(
                 fun({Say, F}, {Acc, St}) ->
                         St1 = F(St),
                         {[#{say => Say, state => fmt(St1)} | Acc], St1}
                 end, {[], Init}, Steps),
    lists:reverse(Rev).

fmt(St) -> maps:map(fun(_, V) -> to_b(V) end, St).

to_b(B) when is_binary(B)  -> B;
to_b(I) when is_integer(I) -> integer_to_binary(I);
to_b(L) when is_list(L)    -> unicode:characters_to_binary(L);
to_b(A) when is_atom(A)    -> atom_to_binary(A, utf8).

ids() -> [P || #{id := P} <- all()].

get(Id) ->
    case [P || #{id := I} = P <- all(), I =:= Id] of
        [P | _] -> P;
        []      -> none
    end.

all() -> [retry(), clock(), floor(), zombie(), atomicity()].

%%%===================================================================
%%% 1. 再送 — 「失敗」と返ったのに入っている
%%%===================================================================

retry() ->
    #{id => <<"retry"/utf8>>,
      title => <<"再送 — 「失敗」と返ったのに入っている"/utf8>>,
      why => <<"クライアントとサーバは別の故障単位で、間にネットワークがある。"
               "だから「届いたのか」が分からない瞬間が必ず存在する。"
               "Cassandra の WriteTimeoutException も FoundationDB の "
               "commit_unknown_result も、この瞬間を「冪等に設計しろ」と"
               "アプリへ押し付けている。"/utf8>>,
      policies => [#{key => <<"naive"/utf8>>, name => <<"素朴な実装"/utf8>>},
                   #{key => <<"session"/utf8>>, name => <<"通番で吸収 (tether)"/utf8>>}],
      steps =>
          run(#{<<"naive"/utf8>> => 100, <<"session"/utf8>> => 100},
              [{<<"在庫は100個。"/utf8>>, fun(S) -> S end},
               {<<"client が「1個売る」を送る。サーバは実行した。"/utf8>>,
                fun(S) -> S#{<<"naive"/utf8>> := 99, <<"session"/utf8>> := 99} end},
               {<<"応答が失われた。client は結果を知らない。"/utf8>>, fun(S) -> S end},
               {<<"client が**同じ要求を送り直す**。"/utf8>>,
                fun(S) ->
                        %% 素朴な実装は再実行する。通番があれば吸収される。
                        S#{<<"naive"/utf8>> := 98}
                end}]),
      verdict => #{<<"naive"/utf8>> => <<"1個しか売っていないのに2個減った"/utf8>>,
                   <<"session"/utf8>> => <<"実行は1回。初回と同じ答えが返る"/utf8>>},
      good => [<<"session"/utf8>>]}.

%%%===================================================================
%%% 2. 時計のずれ — 後から書いたのに負ける
%%%===================================================================

clock() ->
    #{id => <<"clock"/utf8>>,
      title => <<"時計のずれ — 後から書いたのに負ける"/utf8>>,
      why => <<"Cassandra の競合解決はセルごとに「タイムスタンプが大きい方が勝つ」"
               "だけで、そのタイムスタンプは既定でクライアントが生成する。"
               "時計が進んでいる端末が、実時間では先に書いたのに勝ってしまう。"
               "両方に成功が返り、警告も出ない。"/utf8>>,
      policies => [#{key => <<"lww"/utf8>>, name => <<"時刻が大きい方が勝つ (Cassandra)"/utf8>>},
                   #{key => <<"log"/utf8>>, name => <<"到着順で全順序に載せる"/utf8>>}],
      steps =>
          run(#{<<"lww"/utf8>> => <<"old@x"/utf8>>, <<"log"/utf8>> => <<"old@x"/utf8>>},
              [{<<"初期値は old@x。client1 の時計は5秒進んでいる。"/utf8>>, fun(S) -> S end},
               {<<"実時間 t=10.0 : client1 が alice@x を書く（自称 ts=15.0）"/utf8>>,
                fun(S) -> S#{<<"lww"/utf8>> := <<"alice@x"/utf8>>, <<"log"/utf8>> := <<"alice@x"/utf8>>} end},
               {<<"実時間 t=12.0 : client2 が bob@x を書く（正しい ts=12.0）"/utf8>>,
                fun(S) ->
                        %% lww: ts=12.0 < 15.0 なので**負ける**
                        S#{<<"lww"/utf8>> := <<"alice@x"/utf8>>, <<"log"/utf8>> := <<"bob@x"/utf8>>}
                end},
               {<<"両方の client に「成功」が返っている。"/utf8>>, fun(S) -> S end}]),
      verdict => #{<<"lww"/utf8>> => <<"後から書いた bob@x が消えた。誰にも知らされない"/utf8>>,
                   <<"log"/utf8>> => <<"到着順が唯一の順序。後から書いた方が残る"/utf8>>},
      good => [<<"log"/utf8>>]}.

%%%===================================================================
%%% 3. 在庫の下限 — CRDTは収束するが間違う（中心）
%%%===================================================================

floor() ->
    #{id => <<"floor"/utf8>>,
      title => <<"在庫の下限 — CRDTは収束する。しかし間違う"/utf8>>,
      why => <<"「在庫 ≥ 0」は I-confluent ではない。どの2つの正しい状態を"
               "統合しても正しい、が成り立たない。CRDT は収束を保証するが"
               "不変条件は保証しない。しかし**協調が要るのは在庫が尽きるとき"
               "だけ**で、潤沢なうちに持ち分を配ってしまえば、"
               "保持者は問い合わせずに売れる。"/utf8>>,
      policies => [#{key => <<"crdt"/utf8>>, name => <<"CRDTカウンタで統合"/utf8>>},
                   #{key => <<"cas"/utf8>>, name => <<"前提が違えば中止 (CAS)"/utf8>>},
                   #{key => <<"escrow"/utf8>>, name => <<"先に持ち分を配る (escrow)"/utf8>>}],
      steps =>
          run(#{<<"crdt"/utf8>> => <<"在庫5"/utf8>>, <<"cas"/utf8>> => <<"在庫5"/utf8>>,
                <<"escrow"/utf8>> => <<"在庫5"/utf8>>},
              [{<<"在庫は5個。端末Aと端末Bが分断されている。"/utf8>>, fun(S) -> S end},
               {<<"escrow だけ、あらかじめ持ち分を配る（A に2、B に3）。"/utf8>>,
                fun(S) -> S#{<<"escrow"/utf8>> := <<"中央0 / A:2 B:3"/utf8>>} end},
               {<<"A が1個売る。"/utf8>>,
                fun(S) -> S#{<<"crdt"/utf8>> := <<"A: -1"/utf8>>, <<"cas"/utf8>> := <<"在庫4"/utf8>>,
                             <<"escrow"/utf8>> := <<"中央0 / A:1 B:3"/utf8>>} end},
               {<<"**B が7個売ろうとする。**"/utf8>>,
                fun(S) ->
                        S#{<<"crdt"/utf8>>   := <<"A: -1 / B: -7"/utf8>>,
                           <<"cas"/utf8>>    := <<"B は前提(5)が古い → 中止"/utf8>>,
                           <<"escrow"/utf8>> := <<"B は3しか持たない → 3個までしか売れない"/utf8>>}
                end},
               {<<"分断が治り、統合する。"/utf8>>,
                fun(S) ->
                        S#{<<"crdt"/utf8>>   := <<"5 - 1 - 7 = -3"/utf8>>,
                           <<"cas"/utf8>>    := <<"在庫4（Bの売上は無し）"/utf8>>,
                           <<"escrow"/utf8>> := <<"中央0 / A:1 B:0（4個売れた）"/utf8>>}
                end}]),
      verdict =>
          #{<<"crdt"/utf8>> => <<"収束したが**在庫がマイナス**。5個しか無いのに8個売れた"/utf8>>,
            <<"cas"/utf8>>  => <<"正しい。ただし**毎回サーバに問い合わせる**必要がある"/utf8>>,
            <<"escrow"/utf8>> => <<"正しい。しかも**協調なし**。圏外でも売れた"/utf8>>},
      good => [<<"cas"/utf8>>, <<"escrow"/utf8>>]}.

%%%===================================================================
%%% 4. 削除の復活 — zombie data
%%%===================================================================

zombie() ->
    #{id => <<"zombie"/utf8>>,
      title => <<"削除したデータが復活する（zombie data）"/utf8>>,
      why => <<"削除は「墓標(tombstone)」として記録される。墓標は "
               "gc_grace_seconds（既定10日）を過ぎると回収される。"
               "その前に修復を回さないと、削除を知らない複製が戻ってきたとき、"
               "**削除の証拠がもう無い**ので「新しく追加された行」と解釈される。"
               "防ぐ手段は仕組みではなく運用規律しかない。"/utf8>>,
      policies => [#{key => <<"lww"/utf8>>, name => <<"墓標 + gc (Cassandra)"/utf8>>},
                   #{key => <<"log"/utf8>>, name => <<"全順序のログに残す"/utf8>>}],
      steps =>
          run(#{<<"lww"/utf8>> => <<"A:ada B:ada C:ada"/utf8>>, <<"log"/utf8>> => <<"ada"/utf8>>},
              [{<<"3つの複製が同じ行 ada を持っている。"/utf8>>, fun(S) -> S end},
               {<<"1日目: DELETE。ただし複製C は停止中で受け取れない。"/utf8>>,
                fun(S) -> S#{<<"lww"/utf8>> := <<"A:墓標 B:墓標 C:ada"/utf8>>,
                             <<"log"/utf8>> := <<"削除済み（ログに記録）"/utf8>>} end},
               {<<"11日目: gc_grace 経過。A と B の墓標が回収される。"/utf8>>,
                fun(S) -> S#{<<"lww"/utf8>> := <<"A:なし B:なし C:ada"/utf8>>} end},
               {<<"複製C が復帰。読み取ると「Aには無い、Cにはある」。"/utf8>>,
                fun(S) -> S#{<<"lww"/utf8>> := <<"C の ada が「新しい行」と解釈される"/utf8>>} end},
               {<<"read repair が A と B にも書き戻す。"/utf8>>,
                fun(S) -> S#{<<"lww"/utf8>> := <<"A:ada B:ada C:ada（復活）"/utf8>>} end}]),
      verdict =>
          #{<<"lww"/utf8>> => <<"10日前に消したはずの行が、全複製に恒久的に復活した"/utf8>>,
            <<"log"/utf8>> => <<"削除もログの1件。何度再実行しても消えたまま"/utf8>>},
      good => [<<"log"/utf8>>]}.

%%%===================================================================
%%% 5. 複数行の原子性
%%%===================================================================

atomicity() ->
    #{id => <<"atomicity"/utf8>>,
      title => <<"複数行にまたがる原子性が無い"/utf8>>,
      why => <<"Cassandra には複数パーティションのトランザクションが無い。"
               "1文目が成功し2文目がタイムアウトしても、**ロールバックは起きない**。"
               "しかも2文目は後から成功しうるので、時間が経つと勝手に変わりうる。"/utf8>>,
      policies => [#{key => <<"none"/utf8>>, name => <<"トランザクション無し"/utf8>>},
                   #{key => <<"log"/utf8>>, name => <<"1件のログに束ねる"/utf8>>}],
      steps =>
          run(#{<<"none"/utf8>> => <<"alice:100 bob:100（合計200）"/utf8>>,
                <<"log"/utf8>>  => <<"alice:100 bob:100（合計200）"/utf8>>},
              [{<<"alice から bob へ 80 を送る。"/utf8>>, fun(S) -> S end},
               {<<"1文目: alice を 20 にする → 成功。"/utf8>>,
                fun(S) -> S#{<<"none"/utf8>> := <<"alice:20 bob:100（合計120）"/utf8>>} end},
               {<<"2文目: bob を 180 にする → **タイムアウト**。"/utf8>>,
                fun(S) -> S#{<<"none"/utf8>> := <<"alice:20 bob:? （合計120か200か不明）"/utf8>>,
                             <<"log"/utf8>>  := <<"束ごと1件。届いていなければ何も起きていない"/utf8>>} end},
               {<<"ロールバックは起きない。しかも2文目は後から成功しうる。"/utf8>>,
                fun(S) -> S#{<<"none"/utf8>> := <<"時間が経つと勝手に200になるかもしれない"/utf8>>,
                             <<"log"/utf8>>  := <<"再送すれば、全部入るか何も入らないか"/utf8>>} end}]),
      verdict =>
          #{<<"none"/utf8>> => <<"合計が合わない状態が、誰にも気づかれずに残る"/utf8>>,
            <<"log"/utf8>>  => <<"束は1件の記録。途中だけが残ることがない"/utf8>>},
      good => [<<"log"/utf8>>]}.
